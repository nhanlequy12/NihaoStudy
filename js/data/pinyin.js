// Chuyển pinyin có dấu -> số thanh (1-5)
window.toneOf = function (syl) {
  const map = { "āēīōūǖ": 1, "áéíóúǘ": 2, "ǎěǐǒǔǚ": 3, "àèìòùǜ": 4 };
  for (const ch of syl) for (const k in map) if (k.includes(ch)) return map[k];
  return 5;
};
